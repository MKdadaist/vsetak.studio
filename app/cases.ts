export const visibleDirections: Direction[] = directions
  .map((d) => ({ ...d, cases: d.cases.filter((c) => !c.hidden) }))
  .filter((d) => d.cases.length > 0);

export const allCases: CaseItem[] = visibleDirections.flatMap((d) => d.cases);

export function findAnyCase(slug: string): CaseItem | undefined {
  return directions.flatMap((d) => d.cases).find((c) => c.slug === slug);
}

const coverVariants: CoverVariant[] = ["rings", "grid", "waves", "dots"];

// Пока у кейса нет собственных медиа — листаем абстрактные обложки.
function defaultMedia(cover: CoverVariant): MediaItem[] {
  const start = coverVariants.indexOf(cover);
  return coverVariants.map((_, i) => ({
    kind: "cover",
    variant: coverVariants[(start + i) % coverVariants.length],
  }));
}

// Кейс без своей вёрстки собирается из стандартной последовательности.
export function caseBlocks(item: CaseItem): CaseBlock[] {
  if (item.blocks?.length) return item.blocks;
  return [
    { type: "hero" },
    { type: "gallery" },
    { type: "facts" },
    { type: "sections" },
  ];
}

function mediaScreen(m: MediaItem): Screen {
  const kind = m.kind === "html" ? "embed" : m.kind;
  return {
    layout: "free",
    ratio: parseRatio(m.ratio),
    slots: [
      {
        kind,
        src: kind === "cover" ? (m.variant ?? "rings") : (m.src ?? ""),
        alt: m.alt,
        title: m.title,
      },
    ],
  };
}

// Экраны листалки: сохранённые в админке, иначе по одному на каждое медиа кейса.
export function caseScreens(item: CaseItem, media?: MediaItem[]): Screen[] {
  if (!media) {
    const saved = savedScreensFor(item.slug);
    if (saved) return saved;
  }
  return (media ?? item.media ?? defaultMedia(item.cover)).map(mediaScreen);
}

export function firstImage(item: CaseItem): string | undefined {
  for (const screen of caseScreens(item)) {
    const slot = screen.slots.find((s) => s?.kind === "image");
    if (slot) return slot.src;
  }
  for (const block of item.blocks ?? []) {
    if (block.type === "media" && block.item.kind === "image") {
      return block.item.src;
    }
  }
  return undefined;
}

export function findCase(slug: string): CaseItem | undefined {
  return allCases.find((c) => c.slug === slug);
}

export function nextCase(slug: string): CaseItem | undefined {
  if (allCases.length < 2) return undefined;
  const index = allCases.findIndex((c) => c.slug === slug);
  if (index === -1) return undefined;
  return allCases[(index + 1) % allCases.length];
}
