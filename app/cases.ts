export type CaseSection = {
  heading: string;
  text: string;
  // Врезка справа от текста: награда, публикация, отзыв.
  aside?: { image?: string; alt?: string; text: string };
};

export type CoverVariant = "rings" | "grid" | "waves" | "dots";

// Медиа-зона кейса: картинка, видео, iframe с лендингом или произвольная вёрстка.
export type MediaItem = {
  kind: "cover" | "image" | "video" | "embed" | "html";
  variant?: CoverVariant;
  src?: string;
  alt?: string;
  html?: string;
  title?: string;
  ratio?: string;
};

// Ширина блока по сетке страницы кейса (12 колонок):
// full — вся ширина, wide — колонки 4–12, text — колонки 4–10.
export type BlockWidth = "full" | "wide" | "text";

// Страница кейса — упорядоченный список блоков. Этот же формат заполняется
// по эскизам из InDesign и будет читаться и сохраняться визуальным редактором.
export type CaseBlock =
  | { type: "hero" }
  | { type: "gallery"; media?: MediaItem[] }
  | { type: "facts" }
  | { type: "sections"; items?: CaseSection[] }
  | { type: "text"; heading?: string; text: string; width?: BlockWidth }
  | {
      type: "media";
      item: MediaItem;
      caption?: string;
      width?: BlockWidth;
    }
  | {
      type: "grid";
      items: MediaItem[];
      columns?: 2 | 3;
      caption?: string;
      width?: BlockWidth;
    }
  // Все картинки экранов кейса сразу, сеткой — страница-витрина вместо листалки.
  | { type: "tiles"; columns?: 2 | 3 | 4 }
  | { type: "quote"; text: string; author?: string }
  | { type: "divider" };

